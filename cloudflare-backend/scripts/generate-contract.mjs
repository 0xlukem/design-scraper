import Ajv from "ajv";
import standalone from "ajv/dist/standalone/index.js";
import { readFileSync, writeFileSync } from "node:fs";

// schema.json is the source of truth. Fixtures are independent expected outputs
// and must never be rewritten by this generator.
const base = new URL("../src/domain/", import.meta.url);
const schema = JSON.parse(readFileSync(new URL("schema.json", base), "utf8"));
function typeOf(s) {
  if (Object.keys(s).every(k => ["title", "description", "default", "examples"].includes(k))) return "unknown";
  if (s.$ref) {
    const name = s.$ref.replace(/^#\/\$defs\//, "");
    if (!Object.hasOwn(schema.$defs, name)) throw new Error(`Unknown schema reference: ${s.$ref}`);
    return name;
  }
  if (s.anyOf) return s.anyOf.map(typeOf).join(" | ");
  if (s.enum) return s.enum.map(v => JSON.stringify(v)).join(" | ");
  if (s.type === "array") return `Array<${typeOf(s.items)}>`;
  if (s.type === "object") {
    if (s.properties) {
      // These are normalized domain types: validation supplies schema defaults.
      return `{ ${Object.entries(s.properties).map(([k, v]) => `${JSON.stringify(k)}: ${typeOf(v)}`).join("; ")} }`;
    }
    return `Record<string, ${typeof s.additionalProperties === "object" ? typeOf(s.additionalProperties) : "unknown"}>`;
  }
  const primitive = { string: "string", integer: "number", number: "number", boolean: "boolean", null: "null" }[s.type];
  if (!primitive) throw new Error(`Unsupported schema shape: ${JSON.stringify(s)}`);
  return primitive;
}
const types = "// Generated by scripts/generate-contract.mjs from schema.json.\n" +
  Object.entries({ ...schema.$defs, DesignSystem: schema })
    .map(([name, s]) => `export type ${name} = ${typeOf(s)};\n`).join("");
const ajv = new Ajv({ strict: false, code: { source: true, esm: true }, useDefaults: true });
const validator = "// Generated standalone validation; no runtime eval.\n" + standalone(ajv, ajv.compile(schema));
for (const [name, content] of [["types.ts", types], ["validate.js", validator]]) {
  const file = new URL(name, base);
  if (process.argv.includes("--check")) {
    if (readFileSync(file, "utf8") !== content) throw new Error(`${name} is stale; run npm run generate.`);
  } else writeFileSync(file, content);
}
console.log(process.argv.includes("--check") ? "Generated contract is current." : "Generated domain types and standalone validator.");
